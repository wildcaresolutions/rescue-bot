#!/usr/bin/env node
/**
 * Generates workers/.dev.vars from:
 *   - agents/rescue-bot-instruction.md  (generic instruction)
 *   - site/agent-instruction.md          (org-specific instruction)
 *   - .env  (API keys)
 *
 * Run: node workers/scripts/gen-dev-vars.js
 */

import { readFileSync, writeFileSync, existsSync } from 'fs'
import { randomBytes } from 'crypto'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '../..')

// ── 1. Read generic instruction ─────────────────────────────────────────────
const genericInstruction = readFileSync(join(root, 'agents/rescue-bot-instruction.md'), 'utf8')

// ── 2. Read site instruction ──────────────────────────────────────────────────
let siteInstruction = ''
const siteInstructionPath = join(root, 'site/agent-instruction.md')
if (existsSync(siteInstructionPath)) {
  siteInstruction = readFileSync(siteInstructionPath, 'utf8')
} else {
  console.warn('WARN: site/agent-instruction.md not found — SITE_INSTRUCTION will be empty')
}

// ── 3. Read deployment IDs from org.env and secrets from .env or process.env ─
// Secrets precedence: process.env > .env file. process.env is populated either
// by `op run --env-file=.env.op --` (1Password path) or by `scripts/with-env.sh`
// sourcing .env (plain-dotenv path). The direct .env parse below is a final
// fallback for legacy callers that invoke this script outside the Makefile.
function parseEnvFile(path) {
  if (!existsSync(path)) return {}
  return Object.fromEntries(
    readFileSync(path, 'utf8')
      .split('\n')
      .filter(l => l && !l.startsWith('#') && l.includes('='))
      .map(l => { const i = l.indexOf('='); return [l.slice(0, i).trim(), l.slice(i + 1).trim()] }),
  )
}

const envPath = join(root, '.env')
const orgEnvPath = join(root, 'org.env')
// process.env wins; .env fills gaps; org.env contributes non-secret IDs.
const envVars = { ...parseEnvFile(orgEnvPath), ...parseEnvFile(envPath), ...process.env }

// ── 4. Write .dev.vars ────────────────────────────────────────────────────────
// Wrangler's dotenv parser supports multi-line values in double quotes.
// We escape backslashes and double quotes; literal newlines are preserved.
function dotenvValue(str) {
  return '"' + str.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"'
}

// Generate a random SIGNING_SECRET if not in .env
const signingSecret = envVars.SIGNING_SECRET || randomBytes(32).toString('hex')

const devVars = [
  '# Generated by workers/scripts/gen-dev-vars.js — do not edit by hand',
  `SIGNING_SECRET=${signingSecret}`,
  `GENERIC_INSTRUCTION=${dotenvValue(genericInstruction)}`,
  `SITE_INSTRUCTION=${dotenvValue(siteInstruction)}`,
  `AI_GATEWAY_ACCOUNT_ID=${envVars.AI_GATEWAY_ACCOUNT_ID ?? envVars.ACCOUNT_ID ?? ''}`,
  `AI_GATEWAY_ID=${envVars.AI_GATEWAY_ID ?? ''}`,
  `AI_GATEWAY_GOOGLE_BYOK_ALIAS=${envVars.AI_GATEWAY_GOOGLE_BYOK_ALIAS ?? ''}`,
  `AI_GATEWAY_OPENAI_BYOK_ALIAS=${envVars.AI_GATEWAY_OPENAI_BYOK_ALIAS ?? ''}`,
  `AI_GATEWAY_ANTHROPIC_BYOK_ALIAS=${envVars.AI_GATEWAY_ANTHROPIC_BYOK_ALIAS ?? ''}`,
  `AI_GATEWAY_TOKEN=${envVars.AI_GATEWAY_TOKEN ?? ''}`,
  `MAIN_CHAT_MODEL=${envVars.MAIN_CHAT_MODEL ?? ''}`,
  `PHOTO_RECOGNIZER_MODEL=${envVars.PHOTO_RECOGNIZER_MODEL ?? ''}`,
  `REPORT_FROM_EMAIL=${envVars.REPORT_FROM_EMAIL ?? ''}`,
  // Turnstile: use Cloudflare's well-known "always passes" test secret in
  // local dev so the form works without real keys. Real secret is set in
  // prod/test envs via `make cf-push-secrets[-test]`.
  'TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA',
  // PLATFORM_ADMIN_EMAILS is no longer emitted here — it's a plaintext
  // wrangler [vars] value now (rendered from org.env into wrangler.toml by
  // gen-wrangler.js), so `wrangler dev` picks it up from there.
  // Auth bypass: wrangler.template.toml base [vars] now defaults DEV_AUTH_BYPASS=""
  // so a bare `wrangler deploy` ships fail-closed. Set it here (gitignored
  // .dev.vars) so `wrangler dev` still bypasses auth for local development.
  'DEV_AUTH_BYPASS=true',
].join('\n') + '\n'

const devVarsPath = join(__dirname, '../.dev.vars')
writeFileSync(devVarsPath, devVars)
console.log('✓ Generated workers/.dev.vars')
console.log(`  GENERIC_INSTRUCTION: ${genericInstruction.split('\n').length} lines`)
console.log(`  SITE_INSTRUCTION:    ${siteInstruction.split('\n').length} lines`)
console.log(`  SIGNING_SECRET:      ${signingSecret ? 'set' : 'MISSING'}`)
console.log(`  AI_GATEWAY_TOKEN:    ${envVars.AI_GATEWAY_TOKEN ? 'set' : 'MISSING'}`)
