// Load .env if not already injected (op run wrapper does this, but support
// the bare-node case for ergonomics).
function loadEnv() {
  if (process.env.CLOUDFLARE_API_TOKEN) return
  try {
    const dotenv = require('fs').readFileSync(join(REPO_ROOT, '.env'), 'utf8')
    for (const line of dotenv.split('\n')) {
      const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/)
      if (m) process.env[m[1]] = m[2]
    }
  } catch { /* no .env, fall through to validation */ }
}
loadEnv()

