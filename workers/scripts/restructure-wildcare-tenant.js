// ── Apply via CF D1 query API ──────────────────────────────────────────────

async function d1(sql, params) {
  const body = { sql }
  if (params !== undefined) body.params = params
  const res = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/d1/database/${DB_ID}/query`,
    {
      method: 'POST',
      headers: { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    },
  )
  const j = await res.json()
  if (!j.success) {
    console.error('D1 error:', JSON.stringify(j.errors))
    process.exit(1)
  }
  return j.result[0]
}

async function main() {
  // Snapshot the current state for the journal.
  const before = await d1(
    "SELECT length(house_rules) AS hr_len, length(org_config) AS oc_len, custom_instruction IS NOT NULL AS has_ci FROM tenants WHERE slug='wildcare'",
  )
  console.log('before:', before.results[0])

  // Write snapshot to file alongside the script for review/rollback.
  const snapshot = await d1(
    "SELECT house_rules, org_config, bot_overrides, custom_instruction FROM tenants WHERE slug='wildcare'",
  )
  const snapPath = join(__dirname, 'restructure-wildcare-tenant.backup.json')
  writeFileSync(snapPath, JSON.stringify({
    timestamp: new Date().toISOString(),
    db: 'wildcare-db (prod)',
    tenant: 'wildcare',
    before: snapshot.results[0],
  }, null, 2))
  console.log(`backup written to ${snapPath}`)

  // Apply the restructure: new org_config + new house_rules + NULL custom_instruction.
  const upd = await d1(
    `UPDATE tenants
     SET org_config = ?,
         house_rules = ?,
         custom_instruction = NULL,
         custom_instruction_locked = 0,
         custom_instruction_locked_pending_review = 0,
         updated_at = datetime('now')
     WHERE slug = 'wildcare'`,
    [JSON.stringify(NEW_ORG_CONFIG), NEW_HOUSE_RULES],
  )
  console.log(`UPDATE changes: ${upd.meta?.changes ?? '?'}, duration_ms: ${upd.meta?.duration ?? '?'}`)

  // Verify.
  const after = await d1(
    "SELECT length(house_rules) AS hr_len, length(org_config) AS oc_len, custom_instruction IS NULL AS ci_cleared FROM tenants WHERE slug='wildcare'",
  )
  console.log('after: ', after.results[0])
}

main().catch((e) => { console.error(e); process.exit(1) })
