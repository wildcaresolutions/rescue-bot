/**
 * Eval scenario CRUD — the data-layer for /admin/evals[/:id] routes. Auto-
 * generation lives in lib/eval-autogen; the actual scenario runner lives in
 * lib/eval-runner. This module is just the SQL CRUD.
 */
import type { Env } from './types'

export async function listEvalScenarios(env: Env, tenantId: string): Promise<unknown[]> {
  const { results } = await env.DB.prepare(
    'SELECT id, description, expected_behavior, test_message, auto_generated, review_status, reviewed_at, created_at FROM eval_scenarios WHERE tenant_id = ? ORDER BY created_at DESC',
  ).bind(tenantId).all()
  return results
}

export type CreateScenarioResult =
  | { id: string; description: string; expected_behavior: string; test_message: string; auto_generated: number }
  | { error: string; status: number }

export async function createEvalScenario(
  env: Env,
  tenantId: string,
  body: { description?: string; expected_behavior?: string; test_message?: string; auto_generated?: boolean },
): Promise<CreateScenarioResult> {
  const description = typeof body.description === 'string' ? body.description.trim() : ''
  const expectedBehavior = typeof body.expected_behavior === 'string' ? body.expected_behavior.trim() : ''
  const testMessage = typeof body.test_message === 'string' ? body.test_message.trim() : ''

  if (!description || !expectedBehavior || !testMessage) {
    return { error: 'description, expected_behavior, and test_message are required', status: 400 }
  }

  const id = crypto.randomUUID()
  const autoGenerated = body.auto_generated ? 1 : 0

  await env.DB.prepare(
    `INSERT INTO eval_scenarios (id, tenant_id, description, expected_behavior, test_message, auto_generated)
     VALUES (?, ?, ?, ?, ?, ?)`,
  ).bind(id, tenantId, description.slice(0, 1000), expectedBehavior.slice(0, 2000), testMessage.slice(0, 2000), autoGenerated).run()

  return { id, description, expected_behavior: expectedBehavior, test_message: testMessage, auto_generated: autoGenerated }
}

export type UpdateScenarioResult =
  | { id: string; description: string; expected_behavior: string; test_message: string }
  | { error: string; status: number }

/**
 * Edit a scenario's text. Operators were trapped before: a poorly-worded test
 * couldn't be fixed, only deleted. Editing resets the review verdict back to
 * 'unreviewed' (the scenario changed, so the old 👍/👎 no longer applies).
 */
export async function updateEvalScenario(
  env: Env,
  tenantId: string,
  id: string,
  body: { description?: string; expected_behavior?: string; test_message?: string },
): Promise<UpdateScenarioResult> {
  const existing = await loadEvalScenarioById(env, tenantId, id)
  if (!existing) return { error: 'Scenario not found', status: 404 }

  const description = typeof body.description === 'string' ? body.description.trim() : existing.description
  const expectedBehavior = typeof body.expected_behavior === 'string' ? body.expected_behavior.trim() : existing.expected_behavior
  const testMessage = typeof body.test_message === 'string' ? body.test_message.trim() : existing.test_message

  if (!description || !expectedBehavior || !testMessage) {
    return { error: 'description, expected_behavior, and test_message cannot be blank', status: 400 }
  }

  await env.DB.prepare(
    `UPDATE eval_scenarios
       SET description = ?, expected_behavior = ?, test_message = ?,
           review_status = 'unreviewed', reviewed_at = NULL
     WHERE id = ? AND tenant_id = ?`,
  ).bind(description.slice(0, 1000), expectedBehavior.slice(0, 2000), testMessage.slice(0, 2000), id, tenantId).run()

  return { id, description, expected_behavior: expectedBehavior, test_message: testMessage }
}

const REVIEW_STATUSES = new Set(['unreviewed', 'approved', 'rejected'])

/**
 * Set the operator's authoritative verdict on a scenario (👍 approved / 👎
 * rejected, or back to unreviewed). This is the human override of the LLM
 * judge — it persists and is never overwritten by an auto-grade.
 */
export async function reviewEvalScenario(
  env: Env,
  tenantId: string,
  id: string,
  status: string,
): Promise<{ id: string; review_status: string; reviewed_at: string | null } | { error: string; status: number }> {
  if (!REVIEW_STATUSES.has(status)) {
    return { error: "review_status must be 'unreviewed', 'approved', or 'rejected'", status: 400 }
  }
  const reviewedAt = status === 'unreviewed' ? null : new Date().toISOString()
  const res = await env.DB.prepare(
    'UPDATE eval_scenarios SET review_status = ?, reviewed_at = ? WHERE id = ? AND tenant_id = ?',
  ).bind(status, reviewedAt, id, tenantId).run()
  // D1 returns meta.changes; 0 means the scenario didn't exist for this tenant.
  if (res.meta && typeof res.meta.changes === 'number' && res.meta.changes === 0) {
    return { error: 'Scenario not found', status: 404 }
  }
  return { id, review_status: status, reviewed_at: reviewedAt }
}

export async function deleteEvalScenario(env: Env, tenantId: string, id: string): Promise<void> {
  // Delete the scenario's results FIRST. eval_results.scenario_id references
  // eval_scenarios(id) with no ON DELETE CASCADE (migration 0005), and D1
  // enforces foreign keys — so once a scenario has been run (which inserts
  // eval_results rows), deleting just the scenario throws a constraint
  // violation. That surfaced to the operator as "I can't delete the test
  // case": the row stubbornly reappeared because every delete 500'd. Batch
  // both deletes so they apply atomically.
  await env.DB.batch([
    env.DB.prepare('DELETE FROM eval_results WHERE scenario_id = ? AND tenant_id = ?').bind(id, tenantId),
    env.DB.prepare('DELETE FROM eval_scenarios WHERE id = ? AND tenant_id = ?').bind(id, tenantId),
  ])
}

export async function loadEvalScenarioById(
  env: Env,
  tenantId: string,
  scenarioId: string,
): Promise<{ id: string; description: string; expected_behavior: string; test_message: string } | null> {
  return await env.DB.prepare(
    'SELECT * FROM eval_scenarios WHERE id = ? AND tenant_id = ?',
  ).bind(scenarioId, tenantId).first() as { id: string; description: string; expected_behavior: string; test_message: string } | null
}

export async function listEvalResults(
  env: Env,
  tenantId: string,
  scenarioId: string,
): Promise<unknown[]> {
  const { results } = await env.DB.prepare(
    'SELECT id, response, passed, judge_reasoning, created_at FROM eval_results WHERE scenario_id = ? AND tenant_id = ? ORDER BY created_at DESC LIMIT 20',
  ).bind(scenarioId, tenantId).all()
  return results
}
