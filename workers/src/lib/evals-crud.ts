/**
 * Eval scenario CRUD — the data-layer for /admin/evals[/:id] routes. Auto-
 * generation lives in lib/eval-autogen; the actual scenario runner lives in
 * lib/eval-runner. This module is just the SQL CRUD.
 */
import type { Env } from './types'

export async function listEvalScenarios(env: Env, tenantId: string): Promise<unknown[]> {
  const { results } = await env.DB.prepare(
    'SELECT id, description, expected_behavior, test_message, auto_generated, created_at FROM eval_scenarios WHERE tenant_id = ? ORDER BY created_at DESC',
  ).bind(tenantId).all()
  return results
}

export type CreateScenarioResult =
  | { id: string; description: string; expected_behavior: string; test_message: string; auto_generated: number }
  | { error: string; status: number }

export async function createEvalScenario(
  env: Env,
  tenantId: string,
  body: { description?: string; expected_behavior?: string; test_message?: string; auto_generated?: boolean },
): Promise<CreateScenarioResult> {
  const description = typeof body.description === 'string' ? body.description.trim() : ''
  const expectedBehavior = typeof body.expected_behavior === 'string' ? body.expected_behavior.trim() : ''
  const testMessage = typeof body.test_message === 'string' ? body.test_message.trim() : ''

  if (!description || !expectedBehavior || !testMessage) {
    return { error: 'description, expected_behavior, and test_message are required', status: 400 }
  }

  const id = crypto.randomUUID()
  const autoGenerated = body.auto_generated ? 1 : 0

  await env.DB.prepare(
    `INSERT INTO eval_scenarios (id, tenant_id, description, expected_behavior, test_message, auto_generated)
     VALUES (?, ?, ?, ?, ?, ?)`,
  ).bind(id, tenantId, description.slice(0, 1000), expectedBehavior.slice(0, 2000), testMessage.slice(0, 2000), autoGenerated).run()

  return { id, description, expected_behavior: expectedBehavior, test_message: testMessage, auto_generated: autoGenerated }
}

export async function deleteEvalScenario(env: Env, tenantId: string, id: string): Promise<void> {
  await env.DB.prepare(
    'DELETE FROM eval_scenarios WHERE id = ? AND tenant_id = ?',
  ).bind(id, tenantId).run()
}

export async function loadEvalScenarioById(
  env: Env,
  tenantId: string,
  scenarioId: string,
): Promise<{ id: string; description: string; expected_behavior: string; test_message: string } | null> {
  return await env.DB.prepare(
    'SELECT * FROM eval_scenarios WHERE id = ? AND tenant_id = ?',
  ).bind(scenarioId, tenantId).first() as { id: string; description: string; expected_behavior: string; test_message: string } | null
}

export async function listEvalResults(
  env: Env,
  tenantId: string,
  scenarioId: string,
): Promise<unknown[]> {
  const { results } = await env.DB.prepare(
    'SELECT id, response, passed, judge_reasoning, created_at FROM eval_results WHERE scenario_id = ? AND tenant_id = ? ORDER BY created_at DESC LIMIT 20',
  ).bind(scenarioId, tenantId).all()
  return results
}
